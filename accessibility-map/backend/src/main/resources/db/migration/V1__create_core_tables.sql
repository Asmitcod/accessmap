CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_id VARCHAR(64) UNIQUE,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    demo_data BOOLEAN NOT NULL
);

CREATE TABLE features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES places(id),
    type VARCHAR(32) NOT NULL,
    label VARCHAR(80) NOT NULL
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id BIGINT NOT NULL REFERENCES features(id),
    status VARCHAR(32) NOT NULL,
    note VARCHAR(280),
    reported_at TIMESTAMPTZ NOT NULL,
    ttl_days INTEGER NOT NULL
);

CREATE INDEX idx_features_place_id ON features(place_id);
CREATE INDEX idx_reports_feature_reported_at ON reports(feature_id, reported_at DESC);
